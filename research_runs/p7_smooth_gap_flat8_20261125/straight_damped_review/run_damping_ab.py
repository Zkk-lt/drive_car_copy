#!/usr/bin/env python3
"""Vary only the straight-gated predicted yaw damping on a simulated plant."""
import argparse
import csv
import math
import os
from pathlib import Path
import shlex
import statistics
import subprocess


def rms(values):
    return math.sqrt(statistics.mean(v*v for v in values))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--build-dir', type=Path, default=Path('build_smooth_integrated'))
    parser.add_argument('--weights', type=float, nargs='+', default=[0., 1., 2.])
    parser.add_argument('--existing-binary', type=Path,
                        help='reuse an executable generated by this script for a timing repeat')
    parser.add_argument('--cpu', type=int, help='optional taskset CPU for all compared runs')
    args = parser.parse_args()
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=False)
    here = Path(__file__).resolve().parent
    binary = args.existing_binary
    if binary is None:
        tests = here.parents[2] / 'src/move_car/test/control'
        build = args.build_dir.resolve() / 'move_car/CMakeFiles/p6_closed_loop.dir'
        flags = {k: shlex.split(v) for k, v in (line.split(' = ', 1)
                 for line in (build/'flags.make').read_text().splitlines() if ' = ' in line)}
        linker = shlex.split((build/'link.txt').read_text())
        source, binary = output/'closed_loop.cpp', output/'closed_loop'
        subprocess.run(['patch', '-o', str(source), str(tests/'run_p6_closed_loop.cpp'),
                         str(here.parent/'straight_review/noisy_straight_fixture.patch')], check=True)
        text = source.read_text()
        hook = '   if(straighten)straight_blend=rc::P7StraightTrackingReference::condition(spatial,request.reference);'
        if text.count(hook) != 1:
            raise RuntimeError('missing unique straight-reference insertion point')
        source.write_text(text.replace(hook, hook + '''
   if(const char* damping=std::getenv("P7_PROBE_YAW_DAMPING"))
    request.straight_yaw_damping_weight=rc::P7StraightTrackingReference::yawDampingWeight(
      straight_blend,std::stod(damping));'''))
        subprocess.run([linker[0], *flags['CXX_DEFINES'], *flags['CXX_INCLUDES'], *flags['CXX_FLAGS'],
                        '-I'+str(tests), str(source), '-o', str(binary), *linker[linker.index('-o')+2:]], check=True)
    env = {k: v for k, v in os.environ.items() if not k.startswith(('P6_', 'P7_'))}
    for key in ('P6_SPEED_PREVIEW', 'P6_SYNC_PREVIEW', 'P6_ACTUATOR_ALIGNED_PREVIEW',
                'P6_TERMINAL_APPROACH', 'P7_TERMINAL_HANDOFF', 'P6_BOUNDED_FEEDBACK',
                'P6_CONDITIONED_GEOMETRY', 'P6_BASELINE_SEED', 'P6_DELAY_ALIGNED',
                'P6_COMMAND_PROJECTION', 'P6_RESPONSE_BASE', 'P6_RESPONSE_NEAR_SUPPORT',
                'P6_TURN_AWARE_RATE_CONTINUITY', 'P7_STRAIGHT_REFERENCE'):
        env[key] = '1'
    env.update(P6_STEERING_RATE_CONTINUITY_WEIGHT='.05', P6_YAW_RATE_TRACKING_WEIGHT='0',
               P6_MAX_ITERATIONS='2', P6_LATERAL_WEIGHT='39', P6_HEADING_WEIGHT='8.678570922328328',
               P6_SPEED_WEIGHT='6', P6_SMOOTHNESS_WEIGHT='24', P6_TARGET_SPEED='.4',
               P6_MODEL_YAW_GAIN='.9569791928640006')
    rows = []
    prefix = ['taskset', '-c', str(args.cpu)] if args.cpu is not None else []
    for index, weight in enumerate(args.weights):
        raw = output/f'damping_{index}_{weight:g}.csv'
        subprocess.run([*prefix, str(binary.resolve()), str(raw), '10', 'flat_nmpc_slqr', 'none', '8'],
                       env=dict(env, P7_PROBE_YAW_DAMPING=str(weight)), check=True)
        with raw.open(newline='') as summary, Path(str(raw)+'.ticks.csv').open(newline='') as records:
            ticks = list(csv.DictReader(records))
            for row in csv.DictReader(summary):
                path_ticks = [r for r in ticks if r['path'] == row['path']]
                u = [float(r['steering']) for r in path_ticks]
                yaw = [float(r['plant_body_yaw_rate']) for r in path_ticks]
                row.update(weight=weight, index=index,
                           straight_blend_positive=sum(float(r['straight_blend']) > 0 for r in path_ticks),
                           steering_second_difference_rms_rad_s2=rms((c-2*b+a)*900 for a,b,c in zip(u,u[1:],u[2:])),
                           plant_yaw_rate_rms_rad_s=rms(yaw),
                           plant_yaw_acceleration_rms_rad_s2=rms((b-a)*30 for a,b in zip(yaw,yaw[1:])))
                rows.append(row)
    with (output/'damping_summary.csv').open('w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=rows[0])
        writer.writeheader()
        writer.writerows(rows)


if __name__ == '__main__':
    main()
